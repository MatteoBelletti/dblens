using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using DbLens.Core.Analysis.Denormalization;
using DbLens.Core.Analysis.Relationships;
using DbLens.Core.Models;

namespace DbLens.Core.Analysis.Glossary;

/// <summary>A query the user confirmed returns the right figure.</summary>
public sealed record CertifiedQuery(string Name, string Question, string Sql, string CertifiedAt);

public sealed record GlossaryRequest(
    string? Schema = null,
    string[]? Tables = null,
    bool VerifyJoins = false,
    IReadOnlyList<CertifiedQuery>? Certified = null);

public sealed record GlossarySummary(
    int Tables,
    int DocumentedTables,
    int DocumentedColumns,
    int UndocumentedColumns,
    int JoinPaths,
    int CandidateMeasures,
    int CertifiedQueries);

public sealed record GlossaryResult(
    string Database,
    /// <summary>A complete SKILL.md: front matter plus the data map.</summary>
    string Markdown,
    GlossarySummary Summary,
    IReadOnlyList<string> Caveats,
    string? WrittenTo = null);

/// <summary>
/// Renders what dblens knows about a schema as a skill a model can load before writing SQL.
/// Pure. It states meanings only where the schema documents them; a name is never translated into
/// a business meaning, because that is exactly the guess the glossary exists to prevent.
/// </summary>
public static class GlossaryEngine
{
    private static readonly string[] MeasureWords =
    [
        "amount", "importo", "imponibile", "price", "prezzo", "cost", "costo", "value", "valore",
        "qty", "quantity", "quantita", "total", "totale", "revenue", "fatturato", "margin", "margine",
        "discount", "sconto", "tax", "iva", "balance", "saldo",
    ];

    public static GlossaryResult Build(
        string database,
        DatabaseDialect dialect,
        IReadOnlyList<TableDetail> tables,
        IReadOnlyDictionary<(string Schema, string Table), long?> rowCounts,
        InferRelationshipsResult relationships,
        IReadOnlyList<SqlSource> sources,
        IReadOnlyList<CertifiedQuery> certified,
        DateTimeOffset generatedAt)
    {
        var usage = Usage(tables, sources);
        var edges = relationships.Relationships;
        var md = new StringBuilder();
        var slug = Regex.Replace(database.ToLowerInvariant(), "[^a-z0-9]+", "-").Trim('-');
        var measures = 0;

        md.AppendLine("---");
        md.AppendLine($"name: {slug}-data-map");
        md.AppendLine(
            $"description: Data map of the {database} database ({dialect}) generated by dblens — tables, documented " +
            "meanings, join paths with their evidence, candidate measures and certified queries. Use before writing " +
            $"or checking SQL against {database}.");
        md.AppendLine("---");
        md.AppendLine();
        md.AppendLine($"# {database} — data map");
        md.AppendLine();
        md.AppendLine(
            $"Generated by dblens on {generatedAt.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)} from the catalog" +
            (sources.Count > 0 ? $" and {sources.Count} view, routine and workload statement(s)." : "."));
        md.AppendLine();
        md.AppendLine("How to use this map:");
        md.AppendLine("- A meaning shown as `—` is undocumented. Ask the user; do not translate the column name into a meaning.");
        md.AppendLine("- Prefer a certified query when one answers the question, and say that you used it.");
        md.AppendLine("- Join on `declared` or `verified` paths. An `inferred` path is a hypothesis; one `with orphans` drops rows.");
        md.AppendLine("- Answer figures with `query_with_receipt`, and cross-check them when two routes exist.");
        md.AppendLine();

        if (certified.Count > 0)
        {
            md.AppendLine("## Certified queries");
            md.AppendLine();
            foreach (var q in certified.OrderBy(q => q.Name, StringComparer.OrdinalIgnoreCase))
            {
                md.AppendLine($"### {q.Name}");
                md.AppendLine();
                md.AppendLine($"{q.Question} — certified {q.CertifiedAt[..Math.Min(10, q.CertifiedAt.Length)]}.");
                md.AppendLine();
                md.AppendLine("```sql");
                md.AppendLine(q.Sql.Trim());
                md.AppendLine("```");
                md.AppendLine();
            }
        }

        md.AppendLine("## Tables");
        md.AppendLine();

        foreach (var table in tables.OrderBy(t => t.Schema, StringComparer.Ordinal).ThenBy(t => t.Name, StringComparer.Ordinal))
        {
            var name = table.Qualified();
            md.AppendLine($"### {name}{(table.Kind == "table" ? "" : $" ({table.Kind})")}");
            md.AppendLine();

            var facts = new List<string>();
            if (rowCounts.GetValueOrDefault((table.Schema, table.Name)) is { } rows) facts.Add($"~{Num.N0(rows)} rows");
            if (usage.GetValueOrDefault(name) is { Mentions: > 0 } u)
                facts.Add($"referenced by {u.Mentions} SQL source(s)" +
                          (u.Executions > 0 ? $", {Num.N0(u.Executions)} recorded executions" : ""));
            if (facts.Count > 0) md.AppendLine(string.Join(" · ", facts));
            md.AppendLine();
            md.AppendLine($"Meaning: {Meaning(table.Comment)}");
            md.AppendLine();

            var keys = table.KeyColumns(includeReferenced: false);
            md.AppendLine("| Column | Type | Key | Meaning |");
            md.AppendLine("|---|---|---|---|");
            foreach (var c in table.Columns.OrderBy(c => c.OrdinalPosition))
            {
                var key = table.PrimaryKey?.Columns.Contains(c.Name, StringComparer.OrdinalIgnoreCase) == true ? "PK"
                    : keys.Contains(c.Name) ? "FK" : "";
                md.AppendLine($"| `{c.Name}` | {c.FullDataType}{(c.IsNullable ? "" : " not null")} | {key} | {Meaning(c.Comment)} |");
            }
            md.AppendLine();

            var joins = edges
                .Where(e => e.FromTable == name || e.ToTable == name)
                .OrderBy(e => e.FromTable, StringComparer.Ordinal).ThenBy(e => e.ToTable, StringComparer.Ordinal)
                .ToList();
            if (joins.Count > 0)
            {
                md.AppendLine("Joins:");
                foreach (var e in joins)
                    md.AppendLine(
                        $"- `{e.FromTable}({string.Join(", ", e.FromColumns)})` → `{e.ToTable}({string.Join(", ", e.ToColumns)})` — {Label(e)}");
                md.AppendLine();
            }

            var candidates = table.Columns
                .Where(c => ColumnNameVocabulary.IsNumericType(c.DataType) && !keys.Contains(c.Name) && LooksLikeMeasure(c.Name))
                .Select(c => $"`{c.Name}`")
                .ToList();
            if (candidates.Count > 0)
            {
                measures += candidates.Count;
                md.AppendLine($"Candidate measures (by name, unconfirmed): {string.Join(", ", candidates)}");
                md.AppendLine();
            }
        }

        var columns = tables.SelectMany(t => t.Columns).ToList();
        var documented = columns.Count(c => !string.IsNullOrWhiteSpace(c.Comment));

        var caveats = new List<string>();
        if (documented == 0 && columns.Count > 0)
            caveats.Add(
                "No column carries a comment, so the map holds structure and no meanings. Meanings have to come from " +
                "the user; add them as COMMENT ON / MS_Description and regenerate.");

        return new GlossaryResult(
            database,
            md.ToString(),
            new GlossarySummary(
                Tables: tables.Count,
                DocumentedTables: tables.Count(t => !string.IsNullOrWhiteSpace(t.Comment)),
                DocumentedColumns: documented,
                UndocumentedColumns: columns.Count - documented,
                JoinPaths: edges.Count,
                CandidateMeasures: measures,
                CertifiedQueries: certified.Count),
            caveats);
    }

    private static string Meaning(string? comment) =>
        string.IsNullOrWhiteSpace(comment) ? "—" : comment.ReplaceLineEndings(" ").Replace("|", "\\|").Trim();

    private static string Label(RelationshipEdge e) => e.Evidence switch
    {
        RelationshipEvidence.Declared => "declared",
        RelationshipEvidence.Verified => $"verified ({Num.N0(e.RowsCompared ?? 0)} values, no orphans)",
        RelationshipEvidence.VerifiedWithOrphans => $"verified with orphans ({Num.N0(e.OrphanRows ?? 0)} of {Num.N0(e.RowsCompared ?? 0)})",
        _ => $"inferred ({e.Basis})",
    };

    private static bool LooksLikeMeasure(string column) =>
        ColumnNameVocabulary.AggregateFamily(column) == ColumnNameVocabulary.AggregateKind.SumLike
        || column.Split('_', StringSplitOptions.RemoveEmptyEntries)
            .Any(part => MeasureWords.Contains(part, StringComparer.OrdinalIgnoreCase)
                         || part.StartsWith("tot", StringComparison.OrdinalIgnoreCase));

    private static Dictionary<string, (int Mentions, long Executions)> Usage(
        IReadOnlyList<TableDetail> tables, IReadOnlyList<SqlSource> sources)
    {
        var usage = new Dictionary<string, (int Mentions, long Executions)>(StringComparer.Ordinal);
        foreach (var t in tables)
        {
            var rx = new Regex($@"\b{Regex.Escape(t.Name)}\b", RegexOptions.IgnoreCase);
            var hits = sources.Where(s => !(s.Kind == SqlSourceKind.View && s.Name.EndsWith("." + t.Name, StringComparison.OrdinalIgnoreCase))
                                          && rx.IsMatch(s.Sql)).ToList();
            usage[t.Qualified()] = (hits.Count, hits.Sum(s => s.Executions ?? 0));
        }
        return usage;
    }
}
